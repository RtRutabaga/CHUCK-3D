"""The fiend's Infernal script for its subtitles (Claude, 2026-11-18; docs/regions/PHLEGETHOS.md).

The user supplied a strip of blackletter-like glyphs (SourceAssets/UI/InfernalScript/infernal-script-user.jpg: a black
band on top, the glyphs in black ink on white below) and asked that the Pit Fiend's lines be shown "in infernal script
like this". This cuts the strip into its glyphs and writes:
  SourceAssets/UI/InfernalScript/T_InfernalScript.png   the strip as white ink on transparent (alpha = the ink)
  SourceAssets/UI/InfernalScript/glyphs.json            each glyph's box in it (pixels)
  Unreal/Chuck3D/Source/Chuck3D/InfernalScriptData.h    the same for the HUD (ADockHUD draws the fiend's lines with them)
Then Tools/import_infernal_script.py imports the PNG as /Game/Art/UI/T_InfernalScript.

Blender 4.5.14 (its image loader and numpy):
blender --background --factory-startup --python Tools/build_infernal_script.py
"""
from pathlib import Path
import json
import bpy
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'SourceAssets/UI/InfernalScript/infernal-script-user.jpg'
OUT_PNG = ROOT / 'SourceAssets/UI/InfernalScript/T_InfernalScript.png'
OUT_JSON = ROOT / 'SourceAssets/UI/InfernalScript/glyphs.json'
OUT_H = ROOT / 'Unreal/Chuck3D/Source/Chuck3D/InfernalScriptData.h'

img = bpy.data.images.load(str(SRC))
W, H = img.size
px = np.array(img.pixels[:], dtype=np.float32).reshape(H, W, 4)[::-1]   # top row first
lum = px[..., :3] @ np.array([.2126, .7152, .0722], dtype=np.float32)

# The white strip under the black band: rows mostly light.
light = (lum > .6).mean(axis=1)
top = int(np.argmax(light > .5))
strip = lum[top:]
ink = np.clip((.78 - strip) / .5, 0, 1)            # 0 paper, 1 ink (the JPEG's grey fringes in between)
ink[ink < .08] = 0
Hs = strip.shape[0]

# Glyphs: runs of inked columns, gaps of a few pixels inside one bridged, specks dropped.
cols = (ink > .45).sum(axis=0) >= 2
runs, start = [], None
for x, c in enumerate(list(cols) + [False]):
    if c and start is None:
        start = x
    if not c and start is not None:
        runs.append([start, x]); start = None
merged = []
for r in runs:
    if merged and r[0] - merged[-1][1] <= 3:
        merged[-1][1] = r[1]
    else:
        merged.append(r)
glyphs = []
for x0, x1 in merged:
    if x1 - x0 < 5:
        continue
    rows = np.where((ink[:, x0:x1] > .45).any(axis=1))[0]
    if len(rows) < 8:
        continue
    pad = 3
    glyphs.append({'x': max(0, x0 - pad), 'y': max(0, int(rows[0]) - pad), 'w': min(W, x1 + pad) - max(0, x0 - pad),
                   'h': min(Hs, int(rows[-1]) + 1 + pad) - max(0, int(rows[0]) - pad)})

# White ink on transparent, the strip as it is (each glyph keeps its place on the line).
out = bpy.data.images.new('InfernalScript', W, Hs, alpha=True)
rgba = np.ones((Hs, W, 4), dtype=np.float32)
rgba[..., 3] = ink
out.pixels = rgba[::-1].ravel().tolist()
out.filepath_raw = str(OUT_PNG); out.file_format = 'PNG'; out.save()

# The line's reference: the glyphs' common body (the middle of their tops and bottoms), for placing them on a baseline.
body_top = int(np.median([g['y'] for g in glyphs]))
body_bottom = int(np.median([g['y'] + g['h'] for g in glyphs]))
OUT_JSON.write_text(json.dumps({'source': SRC.name, 'width': W, 'height': Hs, 'body_top': body_top, 'body_bottom': body_bottom, 'glyphs': glyphs}, indent=1), encoding='utf-8')
lines = ['// Generated by Tools/build_infernal_script.py from the user\'s Infernal script strip (2026-11-18). Do not edit.',
         '#pragma once', '#include "CoreMinimal.h"', '', 'namespace InfernalScriptData', '{',
         f'    constexpr int32 Width = {W}, Height = {Hs}, BodyTop = {body_top}, BodyBottom = {body_bottom};',
         '    struct FGlyph { int32 X, Y, W, H; };', '    constexpr FGlyph Glyphs[] = {']
lines += [f'        {{{g["x"]}, {g["y"]}, {g["w"]}, {g["h"]}}},' for g in glyphs]
lines += ['    };', '    constexpr int32 GlyphCount = UE_ARRAY_COUNT(Glyphs);', '}', '']
OUT_H.write_text('\n'.join(lines), encoding='utf-8')
print(f'CHUCK_INFERNAL_SCRIPT glyphs={len(glyphs)} strip={W}x{Hs} body={body_top}..{body_bottom}')
