"""Extract seeded buttress dimensions from the existing tree generator's contract.

Writes only a C++ collision metadata header. Does not run Blender, regenerate
art, or modify existing FBX/textures. Seeds/draw order match build_fall_jungle.py.
"""
from pathlib import Path
import math
import random

rows = ['#pragma once', '#include "CoreMinimal.h"', '// Generated by Tools/export_chult_root_profiles.py; centimetres.',
        'namespace ChultRoots {', 'struct FRoot { float Angle, Reach, Top, Width; };']
for name, seed, radius in [('A', 3, 78), ('B', 8, 62)]:
    rng = random.Random(seed)
    rng.uniform(-.04, .04); rng.uniform(-.04, .04)  # trunk lean
    for _ in range(15 * 14):
        rng.uniform(-.05, .05)  # rough trunk rings, before buttresses
    count = rng.randint(5, 6)
    rows.append(f'inline constexpr FRoot {name}[] = {{')
    for k in range(count):
        # Blender FBX -> Unreal reflects Y, as in the existing rig/import contract.
        values = (-math.degrees(k / count * 2 * math.pi + rng.uniform(-.25, .25)),
                  radius * rng.uniform(3.2, 4.4), radius * rng.uniform(4, 6.5), rng.uniform(9, 14))
        rows.append('    {' + ','.join(f'{v:.6f}f' for v in values) + '},')
    rows.append('};')
rows += [
    '// The buttress outer edge (build_fall_jungle.py buttress_extent, 2026-10-13):',
    '// on the bark at the top, leaving it tangentially; T 0 at the top, 1 at the',
    '// ground. The buttress is a lobe of the trunk, broad where it joins it.',
    'inline constexpr float HeightA = 3600.f, HeightB = 2900.f;',
    'inline void FinEdge(const FRoot& R, float BaseRadius, float Height, float T, float& OutRadius, float& OutZ, float& OutHalfWidth)',
    '{',
    '    OutZ = R.Top * FMath::Pow(1.f - T, 2.2f);',
    '    const float Up = FMath::Max(OutZ, 0.f) / (Height * .86f);',
    '    const float Bark = BaseRadius * (1.f - .62f * Up) * (1.f + 1.1f * FMath::Max(0.f, .12f - Up) / .12f);',
    '    OutRadius = Bark + (R.Reach - Bark) * FMath::Pow(T, 1.6f);',
    '    OutHalfWidth = R.Width * 1.25f * (1.2f - .6f * T);',
    '    OutZ -= 6.f;',
    '}',
    '}']
target = Path(__file__).resolve().parents[1] / 'Unreal/Chuck3D/Source/Chuck3D/ChultRootProfiles.h'
target.write_text('\n'.join(rows) + '\n', encoding='utf-8')
print(target)
